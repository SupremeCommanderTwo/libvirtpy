"""Generate ``client/protocol/typed_hints.py``: the type of each typed parameter.

libvirt's setters take lists of ``(name, type, value)`` and the daemon rejects a
value whose integer width differs from the one it expects. The headers document
the type of every named parameter in the comment of its ``VIR_*`` macro ("as a
ullong"); this tool reads those comments from the pinned corpus.

Usage: ``python tools/gen_typed_params.py [--check]``; ``--check`` reports drift.
"""

import argparse
import re
import subprocess
import sys
from pathlib import Path

REPOSITORY_ROOT = Path(__file__).resolve().parent.parent
HEADERS = REPOSITORY_ROOT / ".cache" / "libvirt" / "include" / "libvirt"
OUTPUT = REPOSITORY_ROOT / "src" / "libvirtpy" / "rpc" / "protocol" / "typed_hints.py"

WIRE_TYPES = {
    "int": 1,
    "uint": 2,
    "llong": 3,
    "ullong": 4,
    "double": 5,
    "boolean": 6,
    "string": 7,
}
TYPE_WORDS = "|".join(sorted(WIRE_TYPES, key=len, reverse=True))
COMMENT_AND_MACRO = re.compile(
    r'/\*\*(?P<comment>(?:(?!\*/).)*?)\*/\s*#\s*define\s+VIR_\w+\s+"(?P<name>[\w.]+)"',
    re.DOTALL,
)
DECLARED_TYPE = re.compile(
    rf"\bas\s+(?:an?\s+|the\s+)?(?:VIR_TYPED_PARAM_)?({TYPE_WORDS})\b", re.IGNORECASE
)


def main() -> int:
    """Write (or with ``--check`` verify) the generated hints.

    :returns: the exit status: 1 if ``--check`` finds drift.
    """
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="only report drift")
    arguments = parser.parse_args()

    text = generate()
    if arguments.check:
        drifted = not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text
        if drifted:
            print("typed hints are out of date; run tools/gen_typed_params.py")
        return 1 if drifted else 0

    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT}")
    return 0


def generate() -> str:
    """Build the text of the generated module.

    :returns: the formatted source.
    :raises SystemExit: if the corpus has not been fetched.
    """
    if not HEADERS.exists():
        raise SystemExit("run tools/fetch_samples.py first")

    hints = collect_hints()
    entries = "".join(
        f'    "{name}": {code},\n' for name, code in sorted(hints.items())
    )
    source = (
        '"""GENERATED by tools/gen_typed_params.py. Do not edit.\n\n'
        "Derived from libvirt's headers (LGPL-2.1-or-later).\n\n"
        "The wire type of every named typed parameter that libvirt's headers document\n"
        "(1 int, 2 uint, 3 llong, 4 ullong, 5 double, 6 boolean, 7 string).\n"
        '"""\n\n'
        "from typing import Final\n\n"
        f"TYPED_PARAMETER_HINTS: Final[dict[str, int]] = {{\n{entries}}}\n"
    )
    return _format(source)


def collect_hints() -> dict[str, int]:
    """Read the parameter names and types from the headers.

    A name documented with two different types is dropped: it would be a guess.

    :returns: parameter name -> wire type code.
    """
    found: dict[str, set[int]] = {}
    for header in sorted(HEADERS.glob("*.h")):
        text = header.read_text(encoding="utf-8")
        for match in COMMENT_AND_MACRO.finditer(text):
            declared = DECLARED_TYPE.search(" ".join(match["comment"].split()))
            if declared:
                code = WIRE_TYPES[declared.group(1).lower()]
                found.setdefault(match["name"], set()).add(code)
    return {name: next(iter(codes)) for name, codes in found.items() if len(codes) == 1}


def _format(text: str) -> str:
    """Format source like the rest of the project.

    :param text: Python source.
    :returns: the formatted source.
    """
    result = subprocess.run(
        [sys.executable, "-m", "ruff", "format", "--stdin-filename", str(OUTPUT), "-"],
        input=text,
        capture_output=True,
        text=True,
        check=True,
    )
    return result.stdout


if __name__ == "__main__":
    sys.exit(main())
